CREATE TABLE remoteid (
    id SERIAL PRIMARY KEY, 
    status SMALLINT NOT NULL,
    direction REAL NOT NULL,
    speed_horizontal REAL NOT NULL,
    speed_vertical REAL NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    altitude_baro REAL NOT NULL,
    altitude_geo REAL NOT NULL,
    height_type SMALLINT NOT NULL,
    height REAL NOT NULL,
    horiz_accuracy SMALLINT NOT NULL,
    vert_accuracy SMALLINT NOT NULL,
    baro_accuracy SMALLINT NOT NULL,
    speed_accuracy SMALLINT NOT NULL,
    ts_accuracy SMALLINT NOT NULL,
    timestamp REAL NOT NULL
);

CREATE TABLE droneid (
    timestamp BIGINT NOT NULL,
    pkt_len SMALLINT NOT NULL,
    unk SMALLINT NOT NULL,
    version SMALLINT NOT NULL,
    seq_number SMALLINT NOT NULL,
    state_info SMALLINT NOT NULL,
    serial_number VARCHAR(16) NOT NULL,
    longitude REAL NOT NULL,
    latitude REAL NOT NULL,
    altitude REAL NOT NULL,
    height REAL NOT NULL,
    v_north REAL NOT NULL,
    v_east REAL NOT NULL,
    v_up REAL NOT NULL,
    d_1_angle REAL NOT NULL,
    app_lat REAL NOT NULL,
    app_lon REAL NOT NULL,
    longitude_home REAL NOT NULL,
    latitude_home REAL NOT NULL,
    device_type_id SMALLINT NOT NULL,
    device_type VARCHAR(16) NOT NULL,
    uuid_len SMALLINT NOT NULL,
    uuid VARCHAR(18), 
    crc SMALLINT NOT NULL
);

